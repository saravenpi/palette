package formats

import (
	"fmt"
	"strings"
)

// makoBackgroundAlpha is the opacity the popups keep: translucent enough to
// read as an overlay over the desktop, solid enough that text stays legible
// over a busy wallpaper.
const makoBackgroundAlpha = "f2"

// formatMako renders the colours mako pulls in with `include`. mako reads a
// flat `key=value` config, so the fragment carries only the palette-driven
// colours — the surface, the text, the hairline and the progress bar — and
// gives critical notifications the urgency accent from the same theme.
// Everything else about the popups (size, radius, margins, timeouts) stays in
// ~/.config/mako/config.
func formatMako(t Theme) string {
	var b strings.Builder
	b.WriteString("# Generated by palette sync — do not edit.\n")
	b.WriteString("# Included from ~/.config/mako/config.\n\n")
	b.WriteString(fmt.Sprintf("background-color=%s\n", withAlpha(t.Background, makoBackgroundAlpha)))
	b.WriteString(fmt.Sprintf("text-color=%s\n", t.Foreground))
	b.WriteString(fmt.Sprintf("border-color=%s\n", t.Palette[4]))
	b.WriteString(fmt.Sprintf("progress-color=over %s\n", t.Palette[4]))
	b.WriteString("\n[urgency=critical]\n")
	b.WriteString(fmt.Sprintf("border-color=%s\n", t.Palette[1]))
	b.WriteString(fmt.Sprintf("progress-color=over %s\n", t.Palette[1]))
	return b.String()
}

// withAlpha returns color in mako's #RRGGBBAA form. A value that already
// carries an alpha channel, or that is not a plain six-digit hex colour, is
// returned unchanged so the generated file always stays valid.
func withAlpha(color string, alpha string) string {
	hex := strings.TrimPrefix(strings.ToLower(color), "#")
	if len(hex) != 6 {
		return color
	}
	for _, digit := range hex {
		if !strings.ContainsRune("0123456789abcdef", digit) {
			return color
		}
	}
	return "#" + hex + alpha
}

package formats

import (
	"fmt"
	"strings"
)

// formatYazi renders the theme.toml Yazi deep-merges over its built-in theme.
// Yazi keeps layout, icons and keymaps in yazi.toml and keymap.toml, so this
// file carries only the palette-driven colours. Keys left out fall back to the
// built-in dark/light preset.
func formatYazi(t Theme) string {
	var b strings.Builder
	b.WriteString("# Generated by palette sync — do not edit.\n")
	b.WriteString("# Yazi merges this over its built-in theme at startup.\n\n")
	writeYaziManager(&b, t)
	writeYaziChrome(&b, t)
	writeYaziDialogs(&b, t)
	writeYaziFiletypes(&b, t)
	return b.String()
}

// writeYaziManager renders the [app] and [mgr] sections: the terminal
// background Yazi asks for through OSC 11, the file list and its markers.
func writeYaziManager(b *strings.Builder, t Theme) {
	fmt.Fprintf(b, "[app]\noverall = { bg = %q }\n\n", t.Background)

	b.WriteString("[mgr]\n")
	fmt.Fprintf(b, "cwd = { fg = %q, bold = true }\n", t.Cursor)
	fmt.Fprintf(b, "find_keyword = { fg = %q, bg = %q, bold = true }\n", t.Background, t.Palette[3])
	fmt.Fprintf(b, "find_position = { fg = %q, bg = %q, bold = true }\n", t.Palette[5], t.Palette[0])
	fmt.Fprintf(b, "symlink_target = { fg = %q, italic = true }\n", t.Palette[12])
	fmt.Fprintf(b, "marker_copied = { fg = %q, bg = %q }\n", t.Palette[2], t.Palette[2])
	fmt.Fprintf(b, "marker_cut = { fg = %q, bg = %q }\n", t.Palette[1], t.Palette[1])
	fmt.Fprintf(b, "marker_marked = { fg = %q, bg = %q }\n", t.Palette[6], t.Palette[6])
	fmt.Fprintf(b, "marker_selected = { fg = %q, bg = %q }\n", t.Palette[3], t.Palette[3])
	fmt.Fprintf(b, "count_copied = { fg = %q, bg = %q }\n", t.Background, t.Palette[2])
	fmt.Fprintf(b, "count_cut = { fg = %q, bg = %q }\n", t.Background, t.Palette[1])
	fmt.Fprintf(b, "count_selected = { fg = %q, bg = %q }\n", t.Background, t.Palette[3])
	b.WriteString("border_symbol = \"│\"\n")
	fmt.Fprintf(b, "border_style = { fg = %q }\n\n", t.Palette[8])
}

// writeYaziChrome renders [tabs], [mode], [indicator] and [status], the
// persistent chrome around the file list.
func writeYaziChrome(b *strings.Builder, t Theme) {
	b.WriteString("[tabs]\n")
	fmt.Fprintf(b, "active = { fg = %q, bg = %q, bold = true }\n", t.Background, t.Palette[4])
	fmt.Fprintf(b, "inactive = { fg = %q, bg = %q }\n\n", t.Palette[4], t.Palette[0])

	b.WriteString("[mode]\n")
	fmt.Fprintf(b, "normal_main = { fg = %q, bg = %q, bold = true }\n", t.Background, t.Palette[4])
	fmt.Fprintf(b, "normal_alt = { fg = %q, bg = %q }\n", t.Palette[4], t.Palette[0])
	fmt.Fprintf(b, "select_main = { fg = %q, bg = %q, bold = true }\n", t.Background, t.Palette[1])
	fmt.Fprintf(b, "select_alt = { fg = %q, bg = %q }\n", t.Palette[1], t.Palette[0])
	fmt.Fprintf(b, "unset_main = { fg = %q, bg = %q, bold = true }\n", t.Background, t.Palette[5])
	fmt.Fprintf(b, "unset_alt = { fg = %q, bg = %q }\n\n", t.Palette[5], t.Palette[0])

	b.WriteString("[indicator]\n")
	fmt.Fprintf(b, "parent = { fg = %q }\n", t.Palette[8])
	fmt.Fprintf(b, "current = { fg = %q, bold = true }\n", t.Cursor)
	fmt.Fprintf(b, "preview = { fg = %q, underline = true }\n\n", t.Palette[6])

	b.WriteString("[status]\n")
	fmt.Fprintf(b, "overall = { fg = %q, bg = %q }\n", t.Foreground, t.Background)
	fmt.Fprintf(b, "perm_sep = { fg = %q }\n", t.Palette[8])
	fmt.Fprintf(b, "perm_type = { fg = %q }\n", t.Palette[2])
	fmt.Fprintf(b, "perm_read = { fg = %q }\n", t.Palette[3])
	fmt.Fprintf(b, "perm_write = { fg = %q }\n", t.Palette[1])
	fmt.Fprintf(b, "perm_exec = { fg = %q }\n", t.Palette[6])
	fmt.Fprintf(b, "progress_label = { fg = %q, bold = true }\n", t.Foreground)
	fmt.Fprintf(b, "progress_normal = { fg = %q, bg = %q }\n", t.Palette[2], t.Palette[0])
	fmt.Fprintf(b, "progress_error = { fg = %q, bg = %q }\n\n", t.Palette[3], t.Palette[1])
}

// writeYaziDialogs renders the floating panels: which-key, confirmation,
// spotter, notifications, pickers, input, completion, tasks and help.
func writeYaziDialogs(b *strings.Builder, t Theme) {
	b.WriteString("[which]\n")
	fmt.Fprintf(b, "border = { fg = %q }\n", t.Palette[4])
	fmt.Fprintf(b, "cand = { fg = %q }\n", t.Palette[14])
	fmt.Fprintf(b, "rest = { fg = %q }\n", t.Palette[8])
	fmt.Fprintf(b, "desc = { fg = %q }\n\n", t.Palette[13])

	b.WriteString("[confirm]\n")
	fmt.Fprintf(b, "border = { fg = %q }\n", t.Palette[4])
	fmt.Fprintf(b, "title = { fg = %q, bold = true }\n", t.Palette[4])
	fmt.Fprintf(b, "btn_yes = { fg = %q, bg = %q, bold = true }\n\n", t.Background, t.Palette[2])

	b.WriteString("[spot]\n")
	fmt.Fprintf(b, "border = { fg = %q }\n", t.Palette[4])
	fmt.Fprintf(b, "title = { fg = %q, bold = true }\n", t.Palette[4])
	fmt.Fprintf(b, "tbl_col = { fg = %q }\n", t.Palette[4])
	fmt.Fprintf(b, "tbl_cell = { fg = %q, reversed = true }\n\n", t.Palette[3])

	b.WriteString("[notify]\n")
	fmt.Fprintf(b, "title_info = { fg = %q }\n", t.Palette[2])
	fmt.Fprintf(b, "title_warn = { fg = %q }\n", t.Palette[3])
	fmt.Fprintf(b, "title_error = { fg = %q }\n\n", t.Palette[1])

	b.WriteString("[pick]\n")
	fmt.Fprintf(b, "border = { fg = %q }\n", t.Palette[4])
	fmt.Fprintf(b, "active = { fg = %q, bold = true }\n\n", t.Palette[5])

	b.WriteString("[input]\n")
	fmt.Fprintf(b, "border = { fg = %q }\n", t.Palette[4])
	fmt.Fprintf(b, "title = { fg = %q, bold = true }\n\n", t.Foreground)

	b.WriteString("[cmp]\n")
	fmt.Fprintf(b, "border = { fg = %q }\n", t.Palette[4])
	fmt.Fprintf(b, "active = { fg = %q, bold = true }\n\n", t.Cursor)

	b.WriteString("[tasks]\n")
	fmt.Fprintf(b, "border = { fg = %q }\n", t.Palette[4])
	fmt.Fprintf(b, "hovered = { fg = %q, bold = true }\n\n", t.Palette[5])

	b.WriteString("[help]\n")
	fmt.Fprintf(b, "border = { fg = %q }\n", t.Palette[4])
	fmt.Fprintf(b, "chord = { fg = %q }\n", t.Palette[6])
	b.WriteString("hovered = { reversed = true, bold = true }\n\n")
}

// writeYaziFiletypes renders [filetype], the per-mime and per-kind colours of
// the file list. Declaring the rules replaces Yazi's built-in list, so the
// full set is emitted with palette colours instead of ANSI names.
func writeYaziFiletypes(b *strings.Builder, t Theme) {
	b.WriteString("[filetype]\nrules = [\n")
	fmt.Fprintf(b, "{ mime = \"**/image/*\", fg = %q },\n", t.Palette[3])
	fmt.Fprintf(b, "{ mime = \"**/{audio,video}/*\", fg = %q },\n", t.Palette[5])
	fmt.Fprintf(b, "{ mime = \"**/application/{zip,rar,7z*,tar,gzip,xz,zstd,bzip*,lzma,compress,archive,cpio,arj,xar,ms-cab*}\", fg = %q },\n", t.Palette[1])
	fmt.Fprintf(b, "{ mime = \"**/application/{pdf,doc,rtf}\", fg = %q },\n", t.Palette[6])
	fmt.Fprintf(b, "{ mime = \"vfs/{absent,stale}\", fg = %q },\n", t.Palette[8])
	fmt.Fprintf(b, "{ url = \"*\", is = \"orphan\", bg = %q },\n", t.Palette[1])
	fmt.Fprintf(b, "{ url = \"*\", is = \"exec\", fg = %q },\n", t.Palette[2])
	fmt.Fprintf(b, "{ url = \"*\", is = \"dummy\", bg = %q },\n", t.Palette[1])
	fmt.Fprintf(b, "{ url = \"*/\", is = \"dummy\", bg = %q },\n", t.Palette[1])
	fmt.Fprintf(b, "{ url = \"*/\", fg = %q },\n", t.Palette[4])
	b.WriteString("]\n")
}
